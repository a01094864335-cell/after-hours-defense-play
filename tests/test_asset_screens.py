"""The approved main and staff roster must be real, state-backed game surfaces."""
import unittest
import test_usability as ui


class AssetScreenTests(unittest.TestCase):
    setUpClass = classmethod(ui.UsabilityTests.setUpClass.__func__)
    tearDownClass = classmethod(ui.UsabilityTests.tearDownClass.__func__)
    open = ui.UsabilityTests.open

    def test_main_roster_navigation_and_compact_scroll(self):
        for width, height in [(390, 844), (320, 568)]:
            page = self.open(width, height)
            page.locator('#asset-lobby-host [data-proxy="#roster-open"]').click()
            self.assertTrue(page.locator('#roster').evaluate('d=>d.open'))
            self.assertEqual(page.locator('#asset-roster-host .r-card').count(), 6)
            page.locator('#asset-roster-host [data-group="incoming"]').click()
            self.assertEqual(page.locator('#asset-roster-host .r-card').count(), 11)
            page.locator('#asset-roster-host .r-card').first.click()
            self.assertTrue(page.locator('#recruit-specific').is_disabled())
            page.locator('#roster-back').click()
            if width == 320:
                self.assertTrue(page.locator('#asset-roster-host .r-scroll').evaluate('e=>e.scrollHeight>e.clientHeight'))
            page.locator('#asset-roster-host .r-nav [data-action="close"]').click()
            self.assertFalse(page.locator('#roster').evaluate('d=>d.open'))
            self.assertTrue(page.locator('#asset-lobby-host #asset-lobby').is_visible())

    def test_staff_and_support_actions_keep_original_state_rules(self):
        page = self.open(390, 844)
        page.locator('#asset-lobby-host [data-proxy="#roster-open"]').click()
        page.locator('#asset-roster-host .r-card[data-record="goblin-guard"]').click()
        page.locator('#staff-toggle').click()
        self.assertEqual(page.evaluate('meta.deck.length'), 5)
        page.evaluate('saveChange(d=>{d.tutorialComplete=true;d.owned=["ward"]})')
        page.locator('#staff-toggle').click()
        self.assertEqual(page.evaluate('meta.deck.length'), 4)
        page.locator('#roster-back').click()
        self.assertEqual(page.locator('#asset-roster-host #r-count').inner_text(), '4/5')
        page.locator('#asset-roster-host .r-card[data-record="ghost-courier"]').click()
        page.locator('#staff-toggle').click()
        self.assertTrue(page.evaluate('meta.deck.includes("ghost-courier")'))
        page.locator('#roster-back').click()
        page.locator('#asset-roster-host [data-group="merc"]').click()
        page.locator('#asset-roster-host .r-card[data-record="merc-ward"]').click()
        page.locator('#support-equip').click()
        self.assertEqual(page.evaluate('meta.equipped'), 'ward')
        page.locator('#support-equip').click()
        self.assertNotEqual(page.evaluate('meta.equipped'), 'ward')

    def test_shop_live_wallet_guarantee_and_navigation(self):
        for width, height in [(390, 844), (320, 568)]:
            page = self.open(width, height)
            page.locator('#asset-lobby-host [data-proxy="#shop-open"]').click()
            self.assertTrue(page.locator('#asset-shop-host .purchase').is_disabled())
            page.evaluate('saveChange(d=>{d.coins=240;d.profile.pity=9});renderMeta()')
            page.locator('#asset-shop-host .purchase').click()
            self.assertEqual(page.evaluate('meta.coins'), 120)
            self.assertEqual(page.evaluate('meta.owned.length'), 1)
            self.assertEqual(page.locator('#asset-shop-host #pity').inner_text(), '0/10')
            if page.locator('#hiring-story[open]').count():
                page.locator('[data-hire-close]').click()
            page.locator('#recruit-dialog').get_by_role('button', name='확인', exact=True).click()
            page.locator('#asset-shop-host .tabs [data-tab="items"]').click()
            page.locator('#asset-shop-host [data-item="grade"]').click()
            self.assertEqual(page.evaluate('meta.items.grade'), 1)
            self.assertEqual(page.locator('#asset-shop-host #coins').inner_text(), '100')
            page.locator('#asset-shop-host footer [data-action="roster"]').click()
            self.assertTrue(page.locator('#roster').evaluate('d=>d.open'))
            page.locator('#asset-roster-host [data-action="shop"]').click()
            self.assertTrue(page.locator('#asset-shop-host #pack').is_visible())
            page.locator('#asset-shop-host .close').click()
            self.assertFalse(page.locator('#shop').evaluate('d=>d.open'))

    def test_training_live_upgrades_and_mobile_navigation(self):
        for width, height in [(390, 844), (320, 568)]:
            page = self.open(width, height)
            errors = []
            page.on('pageerror', lambda error: errors.append(str(error)))
            page.locator('#asset-lobby-host [data-proxy="#training-entry"]').click()
            ui = page.locator('#asset-training-host')
            self.assertTrue(ui.locator('#upgrade').is_disabled())
            self.assertTrue(ui.locator('.scroll').evaluate('e=>e.scrollHeight<=e.clientHeight+2'))
            ui.locator('[data-ss-label="effects"]').click()
            self.assertTrue(ui.locator('.scroll').evaluate('e=>e.scrollHeight>e.clientHeight'))
            ui.locator('summary').first.click()
            self.assertTrue(ui.locator('details').first.evaluate('e=>e.open'))
            page.evaluate('saveChange(d=>{d.coins=144});renderTraining()')
            ui.locator('#upgrade').click()
            self.assertEqual(page.evaluate('meta.training.staff'), 2)
            self.assertEqual(page.evaluate('meta.coins'), 136)
            ui.locator('#upgrade').click()
            self.assertEqual(page.evaluate('meta.training.staff'), 3)
            self.assertEqual(page.evaluate('meta.coins'), 126)
            ui.locator('[data-group="merc"]').click()
            ui.locator('#upgrade').click()
            self.assertEqual(page.evaluate('meta.training.merc'), 2)
            self.assertEqual(page.evaluate('meta.coins'), 118)
            page.reload()
            page.wait_for_function('typeof AssetTraining !== "undefined"')
            self.assertEqual(page.evaluate('meta.training.staff'), 3)
            self.assertEqual(page.evaluate('meta.training.merc'), 2)
            page.locator('#asset-lobby-host [data-proxy="#training-entry"]').click()
            page.evaluate('meta.training.staff=30;renderTraining()')
            self.assertTrue(ui.locator('#upgrade').is_disabled())
            page.evaluate('meta.training.staff=3;saveWarning="저장 오류";renderTraining()')
            self.assertTrue(ui.locator('#upgrade').is_disabled())
            page.evaluate('saveWarning="";playing=true;ended=false;renderTraining()')
            self.assertTrue(ui.locator('#upgrade').is_disabled())
            page.evaluate('playing=false;renderTraining()')
            ui.locator('footer [data-action="roster"]').click()
            self.assertTrue(page.locator('#roster').evaluate('d=>d.open'))
            page.keyboard.press('Escape')
            self.assertTrue(page.locator('#training-dialog').is_visible())
            ui.locator('footer [data-action="shop"]').click()
            self.assertTrue(page.locator('#shop').evaluate('d=>d.open'))
            page.keyboard.press('Escape')
            self.assertTrue(page.locator('#training-dialog').is_visible())
            ui.locator('.back').click()
            self.assertTrue(page.locator('#training-dialog').is_hidden())
            self.assertEqual(errors, [])
